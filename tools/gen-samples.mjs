// Make src/ide/samples-data.js from samples/: the small projects in /examples.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'samples');
const files = {};
const walk = (d) => {
  for (const n of readdirSync(d).sort()) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(dir, p)] = readFileSync(p, 'utf8');
  }
};
walk(dir);
writeFileSync(join(root, 'src/ide/samples-data.js'), '// generated by tools/gen-samples.mjs from samples/\nSEE.SampleFiles = ' + JSON.stringify(files, null, 0) + ';\n');
console.log('samples: ' + Object.keys(files).length + ' files');
