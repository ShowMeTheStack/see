// Make src/ide/library-data.js: the index of library/ (titles, levels, files). The programs
// themselves stay in library/ and are fetched when someone opens one.
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { meta } from './libmeta.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'library');
export const CATEGORIES = [
  ['basics', 'First programs'], ['control', 'Decisions and loops'], ['functions', 'Functions and the stack'], ['recursion', 'Recursion'],
  ['arrays', 'Arrays'], ['strings', 'Strings'], ['pointers', 'Pointers'], ['const', 'const, every way round'], ['memory', 'Where things live'],
  ['dynamic', 'malloc, realloc, free'], ['structs', 'Structs, unions, enums'], ['datastruct', 'Lists, stacks, trees, tables'],
  ['algorithms', 'Sorting and searching'], ['funcptr', 'Function pointers'], ['preproc', 'The preprocessor'], ['stdlib', 'The standard library'],
  ['files', 'Files'], ['games', 'Games'], ['math', 'Numbers and maths'], ['classic', 'K&R classics'], ['multifile', 'Programs in several files'],
  ['bugs', 'Find the bug'],
];
export function scan() {
  const out = [];
  for (const [cat] of CATEGORIES) {
    const d = join(lib, cat);
    if (!existsSync(d)) continue;
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) {
        const files = readdirSync(p).filter((f) => /\.(c|h|txt|dat|in)$/.test(f)).sort();
        const main = files.find((f) => f === 'main.c') || files.find((f) => f.endsWith('.c'));
        if (!main) continue;
        const m = meta(readFileSync(join(p, main), 'utf8'));
        out.push(Object.assign({ id: cat + '/' + name, cat, dir: true, files, main }, m));
      } else if (name.endsWith('.c')) {
        const m = meta(readFileSync(p, 'utf8'));
        out.push(Object.assign({ id: cat + '/' + name.replace(/\.c$/, ''), cat, files: [name], main: name }, m));
      }
    }
  }
  return out;
}
if (process.argv[1] && process.argv[1].endsWith('gen-library.mjs')) {
  const idx = scan().map((e) => ({ id: e.id, cat: e.cat, dir: !!e.dir, files: e.files, main: e.main, title: e.title || e.id, about: e.about || '', level: e.level || 1, input: e.input || undefined, args: e.args || undefined, expect: e.expect || undefined }));
  const text = '// generated by tools/gen-library.mjs from library/\nSEE.LibraryCats = ' + JSON.stringify(CATEGORIES) + ';\nSEE.LibraryIndex = ' + JSON.stringify(idx) + ';\n';
  writeFileSync(join(root, 'src/ide/library-data.js'), text);
  console.log('library: ' + idx.length + ' programs');
}
